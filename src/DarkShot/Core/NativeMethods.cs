    public static bool IsCloaked(IntPtr hwnd)
    {
        try
        {
            if (DwmGetWindowAttribute(hwnd, DWMWA_CLOAKED, out uint cloaked, sizeof(uint)) == 0)
                return cloaked != 0;
        }
        catch { /* ignore */ }
        return false;
    }

    public static Rectangle GetExtendedWindowBounds(IntPtr hwnd)
    {
        if (DwmGetWindowAttribute(hwnd, DWMWA_EXTENDED_FRAME_BOUNDS, out RECT dwm, Marshal.SizeOf<RECT>()) == 0)
        {
            var r = dwm.ToRectangle();
            if (r.Width > 0 && r.Height > 0) return r;
        }

        return GetWindowRect(hwnd, out RECT winRect) ? winRect.ToRectangle() : Rectangle.Empty;
    }

    public static string GetWindowTitle(IntPtr hwnd)
    {
        int len = GetWindowTextLength(hwnd);
        if (len <= 0) return string.Empty;
        var sb = new StringBuilder(Math.Min(len + 1, 1024));
        GetWindowText(hwnd, sb, sb.Capacity);
        return sb.ToString();
    }

    public static string GetWindowClass(IntPtr hwnd)
    {
        var sb = new StringBuilder(256);
        GetClassName(hwnd, sb, sb.Capacity);
        return sb.ToString();
    }

    public static int GetWindowPid(IntPtr hwnd)
    {
        GetWindowThreadProcessId(hwnd, out uint pid);
        return unchecked((int)pid);
    }

    public static Point GetCursorPosition()
